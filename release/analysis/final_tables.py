"""Every table in the manuscript, generated from the verified local measurements.

One entry point so no number in the text is typed by hand. Reads the evacuated raw profiles,
recomputes each gate's statistic from them, and prints the tables in order.
"""
from __future__ import annotations

import json, re, sys
from pathlib import Path

import numpy as np

B = 4000
SHORT = {"Llama-3.2-1B-Instruct": "Llama-3.2-1B", "Llama-3.1-8B-Instruct": "Llama-3.1-8B",
         "OLMo-2-1124-7B-Instruct": "OLMo-2-7B", "OLMo-2-1124-13B-Instruct": "OLMo-2-13B",
         "gemma-2-2b-it": "Gemma-2-2B", "gemma-2-9b-it": "Gemma-2-9B",
         "Ministral-8B-Instruct-2410": "Ministral-8B",
         "Mistral-Nemo-Instruct-2407": "Mistral-Nemo-12B",
         "Phi-3-medium-4k-instruct": "Phi-3-medium"}
ORDER = ["Llama-3.2-1B", "Llama-3.1-8B", "OLMo-2-7B", "OLMo-2-13B", "Gemma-2-2B",
         "Gemma-2-9B", "Ministral-8B", "Mistral-Nemo-12B", "Phi-3-medium"]
SERIES = {"Llama": "Llama", "OLMo": "OLMo", "Gemma": "Gemma", "Ministral": "Mistral",
          "Mistral-Nemo": "Mistral", "Phi": "Phi"}


def series_of(m):
    for k, v in SERIES.items():
        if k.lower() in m.lower():
            return v
    return "other"


def judge(tsel, ttest, A, seed=777):
    """Family best against a matched family's best; the count plus the continuous G."""
    rng = np.random.default_rng(seed)
    C = tsel.shape[1]
    val = np.array([ttest[int(np.argmax(tsel[:, e])), e] for e in range(C)])
    K, M, _, _ = A.shape
    null = np.zeros((B, C))
    for e in range(C):
        pick = rng.integers(0, M, size=(B, K))
        fs = A[np.arange(K)[None, :], pick, 0, e]
        fh = A[np.arange(K)[None, :], pick, 1, e]
        null[:, e] = fh[np.arange(B), np.argmax(fs, axis=1)]
    h1, h2 = null[: B // 2], null[B // 2:]
    thr = np.quantile(h1, 0.95, axis=0)
    mu, sd = h1.mean(0), h1.std(0) + 1e-12
    cnt = int((val > thr).sum())
    z = float(((val - mu) / sd).sum())
    zn = ((h2 - mu[None, :]) / sd[None, :]).sum(1)
    return {"n": cnt, "C": C, "count": f"{cnt}/{C}",
            "excess": round(float(np.median((val - mu) / sd)), 2),
            "G": round(z, 1), "p_G": float((1 + (zn >= z).sum()) / (1 + len(zn))),
            "pass": bool(cnt > C // 2 and (1 + (zn >= z).sum()) / (1 + len(zn)) < 0.01)}


def ps(p):
    return "<0.001" if p <= 0.001 else f"{p:.3f}"


def scan(d, pat):
    out = {}
    for mf in sorted(Path(d).glob("meta_*.json")):
        m = re.fullmatch(pat, mf.name)
        if not m:
            continue
        meta = json.loads(mf.read_text())
        npz = Path(d) / mf.name.replace("meta_", "raw_").replace(".json", ".npz")
        if not npz.exists():
            continue
        out[(SHORT.get(meta["model"].split("/")[-1], meta["model"]),) + m.groups()] = (meta, npz)
    return out


def cluster_ci(vals, models, n=10000, seed=20261013):
    by = {}
    for v, m in zip(vals, models):
        by.setdefault(series_of(m), []).append(v)
    ser = sorted(by)
    rng = np.random.default_rng(seed)
    boot = [np.median([x for i in rng.integers(0, len(ser), len(ser)) for x in by[ser[i]]])
            for _ in range(n)]
    return np.median(vals), np.quantile(boot, .025), np.quantile(boot, .975), len(ser)


def main(root):
    R = Path(root)
    print("<!-- generated by final_tables.py -->\n")

    # ---- Gate I ------------------------------------------------------------------
    print("## Table 1 Gate I (variance matching): 10 versus 50 floor draws\n")
    print("The floor is a random direction matched to each target term by term in eigenvalue-weighted variance. "
          "Cells give targets cleared out of 13, the median standardised excess, then p(G).\n")
    print("| Model | Layer | 10 draws, single | **50 draws, single** | 10 draws, syn | **50 draws, syn** |")
    print("|---|---|---|---|---|---|")
    g1 = scan(R / "stageC3", r"meta_(.+?)_L(\d+)\.json")
    g1m = scan(R / "stageC3", r"meta_(.+?)_L(\d+)_m50\.json")
    rows10, rows50, mods = [], [], []
    for m in ORDER:
        c10 = next((v for k, v in g1.items() if k[0] == m), None)
        c50 = next((v for k, v in g1m.items() if k[0] == m), None)
        if not (c10 and c50):
            continue
        lay = c10[0]["layer"]
        cells = []
        for ro in ("single", "syn"):
            for c in (c10, c50):
                z = np.load(c[1])
                r = judge(z[f"emotion|{ro}|tgt_sel"], z[f"emotion|{ro}|tgt_test"],
                          z[f"emotion|{ro}|F5"])
                cells.append(f"{r['count']} ({r['excess']:+.2f}) {ps(r['p_G'])}")
                if ro == "single":
                    (rows10 if c is c10 else rows50).append(r)
        mods.append(m)
        print(f"| {m} | {lay} | {cells[0]} | **{cells[1]}** | {cells[2]} | **{cells[3]}** |")
    for lbl, rs in (("10 draws", rows10), ("50 draws", rows50)):
        med, lo, hi, ns = cluster_ci([r["excess"] for r in rs], mods)
        print(f"\n{lbl}（single）: {sum(r['n'] > 6 for r in rs)}/{len(rs)} models clear a majority; "
              f"median excess {med:+.2f} SD [series-clustered 95% CI {lo:+.2f}, {hi:+.2f}]; {ns} families")
    print()

    # ---- Gate I on fresh scoring rows -------------------------------------------
    print("## Table 2 Gate I: scoring on 32 versus 256 rows (procedure frozen)\n")
    print("| Model | 32 rows, single | **256 rows, single** | 32 rows, syn | **256 rows, syn** |")
    print("|---|---|---|---|---|")
    gb = scan(R / "stageC3", r"meta_(.+?)_L(\d+)_bigtest\.json")
    bg = []
    for m in ORDER:
        c32 = next((v for k, v in g1.items() if k[0] == m), None)
        c256 = next((v for k, v in gb.items() if k[0] == m), None)
        if not (c32 and c256):
            continue
        cells = []
        for ro in ("single", "syn"):
            for c in (c32, c256):
                z = np.load(c[1])
                r = judge(z[f"emotion|{ro}|tgt_sel"], z[f"emotion|{ro}|tgt_test"],
                          z[f"emotion|{ro}|F5"])
                cells.append(f"{r['count']} ({r['excess']:+.2f}) {ps(r['p_G'])}")
                if ro == "single" and c is c256:
                    bg.append((m, r))
        print(f"| {m} | {cells[0]} | **{cells[1]}** | {cells[2]} | **{cells[3]}** |")
    if bg:
        med, lo, hi, _ = cluster_ci([r["excess"] for _, r in bg], [m for m, _ in bg])
        print(f"\n256 rows (single): majority in {sum(r['n'] > 6 for _, r in bg)}/{len(bg)} / "
              f"median excess SD {med:+.2f} [{lo:+.2f}, {hi:+.2f}]")
    print()

    # ---- Gate II -----------------------------------------------------------------
    for tag, pat, title, nn in (
            ("lp30", r"LP_(.+?)_L(\d+)\.json", "Table 3 Gate II (30 random partitions)", 30),
            ("lp100", r"LP_(.+?)_L(\d+)_p100\.json", "Table 4 Gate II (100 random partitions)", 100)):
        fs = {}
        for f in sorted((R / "stageLP").glob("LP_*.json")):
            m = re.fullmatch(pat, f.name)
            if m:
                d = json.loads(f.read_text())
                fs[SHORT.get(d["model"].split("/")[-1], d["model"])] = d
        if not fs:
            continue
        print(f"## {title}\n")
        print("| Model | single | syn |")
        print("|---|---|---|")
        for m in ORDER:
            d = fs.get(m)
            if not d:
                continue
            def c(ro):
                r = d["results"][ro]
                k = [x for x in r if x.startswith("count_vs")][0]
                return f"{r[k]} ({r['median_excess_sd']:+.2f}) p={r['p_G']:.4f}"
            print(f"| {m} | {c('single')} | {c('syn')} |")
        for ro in ("single", "syn"):
            ok = sum(1 for d in fs.values() if d["results"][ro]["pass"])
            print(f"\n{ro}: {ok}/{len(fs)} models pass; p(G) in all cells "
                  f"{min(d['results'][ro]['p_G'] for d in fs.values()):.4f}")
        print()

    # ---- Gate II' ---------------------------------------------------------------
    print("## Table 5 Gate II (activation-clustered partitions, decodability matched from above)\n")
    print("A draw is accepted only if its held-out probe quality is at least the emotion partition's. Below ten accepted draws the null has no spread and the model is unmeasurable.\n")
    print("| Model | emotion AUC | accepted/tried | candidate AUC max | single | syn |")
    print("|---|---|---|---|---|---|")
    sp = {}
    for f in sorted((R / "stageSPact").glob("SPact_*.json")):
        d = json.loads(f.read_text())
        sp[SHORT.get(d["model"].split("/")[-1], d["model"])] = d
    meas = 0
    for m in ORDER:
        d = sp.get(m)
        if not d:
            continue
        seen = d.get("candidate_auc_seen") or []
        top = f"{max(seen):.4f}" if seen else "—"
        def c(ro):
            r = (d.get("results") or {}).get(ro)
            if not r:
                return "**unmeasurable**"
            k = [x for x in r if x.startswith("count_vs")][0]
            return f"{r[k]} ({r['median_excess_sd']:+.2f}) p={r['p_G']:.3f}"
        if d.get("measurable", True) and d.get("results"):
            meas += 1
        print(f"| {m} | {d['emotion_probe_auc']:.4f} | {d['n_part']}/{d['n_tried']} | {top} "
              f"| {c('single')} | {c('syn')} |")
    for ro in ("single", "syn"):
        q = [d for d in sp.values() if d.get("results")]
        ok = sum(d["results"][ro]["pass"] for d in q)
        print(f"\n{ro}: {ok} of {len(q)} measurable models pass (of {len(sp)} total)")
    print()

    # ---- Gate III ----------------------------------------------------------------
    print("## Table 6 Gate III (encoding transfer), with the same-context and gradient controls\n")
    print("The prefix `Code: {table}\\n\\nEvent: {text}\\n\\n` is identical in both cells; "
          "only the final cue and the readout vocabulary differ.\n")
    print("| Model | Codebook | Draws | emotion-word readout | code readout | gradient (control) |")
    print("|---|---|---|---|---|---|")
    sc = scan(R / "stageSC", r"meta_(.+?)_L(\d+)_(word|code)(\d)(_grad|_m50)?\.json")
    byk = {}
    for (m, _tag, lay, cue, cb, suf), v in sc.items():
        byk[(m, cb, cue, suf or "")] = v
    for m in ORDER:
        for cb in ("1", "2"):
            cells = []
            for cue, suf in (("word", ""), ("code", ""), ("code", "_grad")):
                v = byk.get((m, cb, cue, suf))
                if v is None:
                    cells.append("—"); continue
                z = np.load(v[1])
                fam = "grad" if suf == "_grad" else "emotion"
                r = judge(z[f"{fam}|{cue}|tgt_sel"], z[f"{fam}|{cue}|tgt_test"],
                          z[f"{fam}|{cue}|F5"])
                cells.append(f"{r['count']} ({r['excess']:+.2f}) {ps(r['p_G'])}")
            if all(c == "—" for c in cells):
                continue
            n50 = byk.get((m, cb, "word", "_m50"))
            print(f"| {m} | {cb} | {'10/50' if n50 else '10'} | {cells[0]} | {cells[1]} "
                  f"| {cells[2]} |")
    print()
    print("### Fifty floor draws, codebook 1\n")
    print("| Model | emotion words | codes |")
    print("|---|---|---|")
    for m in ORDER:
        cells = []
        for cue in ("word", "code"):
            v = byk.get((m, "1", cue, "_m50"))
            if v is None:
                cells.append("—"); continue
            z = np.load(v[1])
            r = judge(z[f"emotion|{cue}|tgt_sel"], z[f"emotion|{cue}|tgt_test"],
                      z[f"emotion|{cue}|F5"])
            cells.append(f"{r['count']} ({r['excess']:+.2f}) {ps(r['p_G'])}")
        if any(c != "—" for c in cells):
            print(f"| {m} | {cells[0]} | {cells[1]} |")
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
